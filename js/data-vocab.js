/* ---------- Сборка словаря ---------- */
(function () {
  const GENDER = { ο: "м", η: "ж", το: "ср" };
  const out = [];
  const byKey = new Map();
  for (const [kind, groups] of Object.entries(window.VOCAB_RAW)) {
    for (const [topic, block] of Object.entries(groups)) {
      block.trim().split("\n").forEach((line) => {
        let [raw, ru, lvl, ex] = line.split("|").map((s) => (s || "").trim());
        if (!raw || !ru) return;
        // уточнение в скобках → подсказка
        let hint = "";
        const m = raw.match(/\s*\(([^)]+)\)\s*$/);
        let gr = raw;
        if (m) { hint = m[1]; gr = raw.slice(0, m.index).trim(); }
        const key = kind + ":" + raw;
        // один и тот же греческий вариант без уточнения — объединяем переводы
        const dupKey = kind + ":" + gr + (hint ? "(" + hint + ")" : "");
        if (byKey.has(dupKey)) {
          const it = byKey.get(dupKey);
          const have = it.ru.split(/[;,]\s*/);
          const add = ru.split(/[;,]\s*/).filter((x) => !have.includes(x));
          if (add.length) it.ru += "; " + add.join(", ");
          if (lvl < it.lvl) it.lvl = lvl;
          return;
        }
        const item = { id: key, kind, topic, gr, ru, lvl, hint };
        if (ex) item.ex = ex;
        if (kind === "nouns") {
          const first = gr.split("/")[0];
          const sp = first.indexOf(" ");
          item.art = first.slice(0, sp);
          item.word = first.slice(sp + 1);
          item.gender = GENDER[item.art] || null; // множественное (οι/τα) — без рода в упражнении
          if (item.art === "τα") item.plural = true;
          if (item.art === "οι") item.plural = true;
        } else if (kind === "adjectives") {
          item.word = gr.split(" ")[0];
        } else {
          item.word = gr.split("/")[0];
        }
        byKey.set(dupKey, item);
        out.push(item);
      });
    }
  }
  window.VOCAB = out;
})();
